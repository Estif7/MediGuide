@Injectable({
  providedIn: 'root',
})
export class TranslationService {
  private readonly storageKey = 'medi_guide_lang';
  readonly currentLang = signal<Language>(this.getInitialLang());

  readonly isAmharic = computed(() => this.currentLang() === 'am');

  private getInitialLang(): Language {
    const saved = localStorage.getItem(this.storageKey);
    return saved === 'am' || saved === 'en' ? saved : 'en';
  }

  setLanguage(lang: Language) {
    this.currentLang.set(lang);
    localStorage.setItem(this.storageKey, lang);
  }

  toggleLanguage() {
    this.setLanguage(this.currentLang() === 'en' ? 'am' : 'en');
  }

  t(key: string): string {
    const lang = this.currentLang();
    return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS['en']?.[key] ?? key;
  }
}
